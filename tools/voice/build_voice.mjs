// Packs the rendered voice clips into the game: game/data/vo_*.js (base64 AAC, loaded with their part of the game)
// and src/voice_index.js (normalised text → pack, clip, seconds). Run from the repo root after a render:
//   node tools/voice/build_voice.mjs voice/render
import fs from 'fs'; import path from 'path'; import { execFileSync } from 'child_process';
import { GLOSSARY } from '../../src/text.js';
import { norm } from '../../src/core/voicenorm.js';

const dir = process.argv[2] || 'voice/render';
const s = fs.readFileSync(path.join(dir, 'manifest.js'), 'utf8');
const M = JSON.parse(s.slice(s.indexOf('{'), s.lastIndexOf('}') + 1));

// which pack a game part goes into (Lépcsőház is split so no single file gets too big)
const packOf = g => g.startsWith('ep') ? 'vo_' + g : g.startsWith('hub/') ? 'vo_hub'
  : g === 'lepcsohaz/walks' ? 'vo_lh_walks' : g === 'lepcsohaz/school' ? 'vo_lh_school' : 'vo_lh';
// shown text → what the player reads on screen (glossary links show their label or term)
const shown = t => t.replace(/\[\[([a-z0-9]+)(?:\|([^\]]+))?\]\]/g, (_, k, l) => l || GLOSSARY[k]?.term || k);

const packs = {}, index = {}; let n = 0, bytes = 0;
const root = path.dirname(dir);
for (const l of M.lines) {
  if (!l.file) continue;
  const f = path.join(path.dirname(dir), l.file); if (!fs.existsSync(f)) { console.warn('missing', f); continue; }
  const key = norm(shown(l.text)); if (!key || key.length < 2) continue;
  const pack = packOf(l.group);
  const dur = +execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString().trim();
  if (index[key]) continue;                        // same words already voiced elsewhere: reuse
  const buf = fs.readFileSync(f); bytes += buf.length;
  (packs[pack] ??= {})[l.id] = buf.toString('base64');
  index[key] = [pack, l.id, Math.round(dur * 100) / 100]; n++;
}
fs.mkdirSync('game/data', { recursive: true });
for (const [p, clips] of Object.entries(packs)) {
  fs.writeFileSync(`game/data/${p}.js`, `window.SK_DATA=window.SK_DATA||{};window.SK_DATA[${JSON.stringify(p)}]={"vo":${JSON.stringify(clips)}};`);
  console.log(p.padEnd(14), Object.keys(clips).length, 'clips', (fs.statSync(`game/data/${p}.js`).size / 1e6).toFixed(1), 'MB');
}
// which voice packs to fetch when the game loads one of its asset packs
const PRELOAD = { hub: ['vo_hub'], field: ['vo_hub'], rogue: ['vo_lh', 'vo_lh_walks', 'vo_lh_school'] };
for (let i = 1; i <= 9; i++) PRELOAD['ep' + i] = ['vo_ep' + i];
fs.writeFileSync('src/voice_index.js', `// generated by tools/voice/build_voice.mjs: do not edit by hand\nexport const VO_PRELOAD = ${JSON.stringify(PRELOAD)};\nexport const VO_INDEX = ${JSON.stringify(index)};\n`);
console.log(`\n${n} clips, ${(bytes / 1e6).toFixed(1)} MB audio, index → src/voice_index.js`);
